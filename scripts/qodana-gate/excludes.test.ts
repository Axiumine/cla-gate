import { expect, test } from 'vitest';
import { uncommentedExcludes } from './excludes.ts';

const HEAD = 'version: "1.0"\nlinter: jetbrains/qodana-js:2026.2\n';

test('a file without an exclude list has no uncommented entry', () => {
  expect(uncommentedExcludes(HEAD)).toEqual([]);
});

test('an entry with a comment line directly above it is fine, however many entries follow', () => {
  const text = `${HEAD}exclude:\n  # generated by the build\n  - name: All\n    paths:\n      - dist\n  # vendored\n  - name: JSUnusedGlobalSymbols\n    paths:\n      - vendor\n`;
  expect(uncommentedExcludes(text)).toEqual([]);
});

test('the first entry needs its own comment: a comment above the exclude key does not count', () => {
  const text = `${HEAD}# why\nexclude:\n  - name: All\n    paths:\n      - dist\n`;
  expect(uncommentedExcludes(text)).toEqual(['- name: All']);
});

test('only the entry without a comment is named, and a blank line between comment and entry does not count', () => {
  const text = `${HEAD}exclude:\n  # generated\n  - name: All\n    paths:\n      - dist\n  - name: Second\n    paths:\n      - a\n  # spaced\n\n  - name: Third\n`;
  expect(uncommentedExcludes(text)).toEqual(['- name: Second', '- name: Third']);
});

test('the paths below an entry are not entries, and a comment inside the entry does not justify the next one', () => {
  const text = `${HEAD}exclude:\n  # generated\n  - name: All\n    paths:\n      # a note on the path\n      - dist\n  - name: Next\n`;
  expect(uncommentedExcludes(text)).toEqual(['- name: Next']);
});

test('the list ends at the next top-level key: a list item of another key is not an exclusion', () => {
  const text = `${HEAD}exclude:\n  # generated\n  - name: All\nbootstrap:\n  - npm install\nprofile:\n  - name: qodana.recommended\n`;
  expect(uncommentedExcludes(text)).toEqual([]);
});

test('a list that ends the file is read to its last line', () => {
  expect(uncommentedExcludes(`${HEAD}exclude:\n  - name: Last`)).toEqual(['- name: Last']);
});

test('list items before the exclude key are not exclusions', () => {
  expect(uncommentedExcludes(`bootstrap:\n  - npm install\n${HEAD}exclude:\n  # why\n  - name: All\n`)).toEqual([]);
});
